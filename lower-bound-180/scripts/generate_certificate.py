#!/usr/bin/env python3
"""Emit untrusted Lean data and kernel-checked arithmetic witness obligations.

Coefficient data has no mathematical authority by itself. The generated witness
theorems are conditional on preceding rows being valid; analytic row validity and
the final contradiction are assembled separately. No native_decide is emitted.
"""
from __future__ import annotations

import argparse
from fractions import Fraction as F
import json
from pathlib import Path

from benchmark_int_tree import Trees
from certificate_model import CertificateModel

BASE = 'KMedian180.Certificate'
DATA = BASE + '.Data'


def lookup(entries):
    """Entries are (first accepted key, Lean leaf expression), in increasing order."""
    if not entries:
        return '.empty'
    if len(entries) == 1:
        return entries[0][1]
    middle = len(entries) // 2
    return f'(.branch {entries[middle][0]} {lookup(entries[:middle])} {lookup(entries[middle:])})'


def combination(terms, source):
    if not terms:
        return '.zero'
    if len(terms) == 1:
        i, m = terms[0]
        return f'(.term {i} {m} {source(i)})'
    middle = len(terms) // 2
    return f'(.add {combination(terms[:middle], source)} {combination(terms[middle:], source)})'


def add_combinations(names):
    if not names:
        return '.zero'
    if len(names) == 1:
        return names[0]
    mid = len(names) // 2
    return f'(.add {add_combinations(names[:mid])} {add_combinations(names[mid:])})'


def conjunction(proofs):
    if not proofs:
        return 'True.intro'
    if len(proofs) == 1:
        return proofs[0]
    mid = len(proofs) // 2
    return f'⟨{conjunction(proofs[:mid])}, {conjunction(proofs[mid:])}⟩'


class Generator:
    def __init__(self, model):
        self.model = model
        self.root = model.root
        self.owners = {}
        self.files = []

    def write(self, module, imports, namespace, lines, trees=None):
        header = [f'import {m}' for m in sorted(set(imports))]
        header += ['', '/-! Generated by scripts/generate_certificate.py. All numerical facts require Lean proofs. -/',
                   '', f'namespace {namespace}', f'open {BASE}', 'open scoped BigOperators', '',
                   'set_option maxRecDepth 4096', 'set_option maxHeartbeats 0', '']
        if '.Witness' in module and '.Block' in module and '.Witness4.' not in module:
            header = [line.replace('maxRecDepth 4096', 'maxRecDepth 16384') for line in header]
        if any(part in namespace for part in ('.Witness', '.Analytic', '.Clients', '.Catalogue')):
            header.insert(len(set(imports)) + 1, 'set_option linter.style.setOption false')
            header.insert(len(set(imports)) + 2, 'set_option linter.style.longLine false')
        if trees:
            header += [line.replace('def tree', 'private def tree', 1) for line in trees.definitions]
        text = '\n'.join(header + lines + ['', f'end {namespace}', ''])
        path = self.root / (module.replace('.', '/') + '.lean')
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
        self.files.append(path)

    def data(self):
        graph, checker = self.model.graph, self.model.checker
        bids = sorted(graph['used_bids'])
        for part in range(0, len(bids), 100):
            module = f'{DATA}.Bids{part // 100:03}'
            trees = Trees()
            nodes = [(i, trees.tree(checker.grows[i], 8)) for i in bids[part:part + 100]]
            lines = []
            for i, node in nodes:
                lines += [f'-- Original bid row {i}: {graph["bids"][i]!r}',
                          f'def bid{i} : IntTree 8 := {trees.render(node)}']
                self.owners[f'bid{i}'] = module
            self.write(module, [BASE + '.TreeWitness'], DATA, lines, trees)

        clients = [i for i in sorted(graph['used_rows']) if graph['rows'][i][0] == 'client']
        for part in range(0, len(clients), 16):
            module = f'{DATA}.Clients{part // 16:03}'
            trees, row_nodes = Trees(), []
            for i in clients[part:part + 16]:
                row_nodes.append((i, [(t, trees.tree(block, 8)) for t, block in sorted(self.model.blocks(i).items())]))
            lines = []
            for i, nodes in row_nodes:
                entries = [(t, f'(.entry {t} {trees.render(node)})') for t, node in nodes]
                lines += [f'-- Original client row {i}; type index {graph["rows"][i][1]}.',
                          f'def row{i} : IntegerRow := .blocks {lookup(entries)}']
                self.owners[f'row{i}'] = module
            self.write(module, [BASE + '.TreeWitness'], DATA, lines, trees)

        cuts = sorted({graph['rows'][i][2] for i in graph['used_rows'] if graph['rows'][i][0] == 'product'})
        factors_module = DATA + '.Factors'
        lines = []
        for step in cuts:
            event = graph['witnesses'][step]
            co = {int(t): F(a) for t, a in event['direction']}
            bound = F(event['bound'])
            factors = [(t, bound - co.get(t, F(0))) for t in range(checker.T)]
            entries = [(t, f'(.entry {t} (({v.numerator}), {v.denominator}))') for t, v in factors]
            lines.append(f'def factors{step} : LookupTree (ℤ × ℕ) := {lookup(entries)}')
        self.write(factors_module, [BASE + '.TreeWitness'], DATA, lines)

        products = [i for i in sorted(graph['used_rows']) if graph['rows'][i][0] == 'product']
        for part in range(0, len(products), 128):
            module = f'{DATA}.Products{part // 128:03}'
            lines, imports = [], [factors_module]
            for i in products[part:part + 128]:
                _, bid, step = graph['rows'][i]
                lines.append(f'def row{i} : IntegerRow := .product bid{bid} factors{step}')
                imports.append(self.owners[f'bid{bid}'])
                self.owners[f'row{i}'] = module
            self.write(module, imports, DATA, lines)

        refined = [i for i in sorted(graph['used_rows']) if graph['rows'][i][0] == 'refined']
        for part in range(0, len(refined), 128):
            module = f'{DATA}.Refined{part // 128:03}'
            lines, imports = [], []
            for i in refined[part:part + 128]:
                _, source, increment = checker.extra[i - checker.base_end]
                assert source == graph['rows'][i][1]
                lines.append(f'def row{i} : IntegerRow := .refine row{source} ({increment})')
                imports.append(self.owners[f'row{source}'])
                self.owners[f'row{i}'] = module
            self.write(module, imports, DATA, lines)

        starts = {row[1]: i - row[2] for i, row in enumerate(graph['rows']) if row[0] == 'lift'}
        entries = []
        for bid in bids:
            if bid in starts:
                start = starts[bid]
                entries.append((start, f'(.range {start} {start + checker.T} (fun i => .lift (i - {start}) bid{bid}))',
                                self.owners[f'bid{bid}']))
        for i in clients + products + refined:
            entries.append((i, f'(.entry {i} row{i})', self.owners[f'row{i}']))
        entries.sort()
        chunks = []
        for part in range(0, len(entries), 128):
            module = f'{DATA}.Index{part // 128:03}'
            name = f'index{part // 128}'
            chunk = entries[part:part + 128]
            self.write(module, [owner for _, _, owner in chunk], DATA,
                       [f'def {name} : LookupTree IntegerRow := {lookup([(i, e) for i, e, _ in chunk])}'])
            chunks.append((chunk[0][0], name, module))

        def join_chunks(chunks):
            if len(chunks) == 1:
                return chunks[0][1]
            mid = len(chunks) // 2
            return f'(.branch {chunks[mid][0]} {join_chunks(chunks[:mid])} {join_chunks(chunks[mid:])})'

        self.write(DATA + '.Rows', [m for _, _, m in chunks], DATA,
                   [f'def rowIndex : LookupTree IntegerRow := {join_chunks(chunks)}',
                    'def rows (i : ℕ) : IntegerRow := rowIndex.get (.lift 0 .zero) i'])

        trees = Trees()
        upper = trees.tree({j: u for j, u in enumerate(checker.U) if u}, 8)
        self.write(DATA + '.Budget', [BASE + '.TreeWitness'], DATA,
                   [f'def budgetUpper : IntTree 8 := {trees.render(upper)}'], trees)
        samples = [(j, F(value)) for j, value in enumerate(self.model.data['xs'])]
        sample_entries = [(j, f'(.entry {j} (({v.numerator} : ℚ) / {v.denominator}))') for j, v in samples]
        lines = [f'private def sampleIndex : LookupTree ℚ := {lookup(sample_entries)}',
                 'def sample (j : ℕ) : ℚ := if j < 209 then sampleIndex.get 1 j else 1',
                 'def activation (t : ℕ) : ℚ := (81 / 80 : ℚ) ^ t',
                 'theorem sample_zero : sample 0 = 0 := by decide +kernel',
                 'theorem sample_terminal (j : ℕ) (hj : 209 ≤ j) : sample j = 1 := by',
                 '  simp only [sample, if_neg (not_lt.mpr hj)]',
                 'theorem samples_valid : ∀ j : Fin 256, (0 : ℚ) ≤ sample j ∧ sample j ≤ 1 ∧',
                 f'    ({checker.D} : ℚ) * (1 - sample j) ≤ (budgetUpper.coeff j : ℚ) := by decide +kernel']
        self.write(DATA + '.Grid', [DATA + '.Budget'], DATA, lines)

    def witness(self, step):
        cert, cutoff = self.model.witness(step)
        checker = self.model.checker
        D, S, mu = checker.D, checker.S, cert['mu']
        terms = [(i, m) for i, m in cert['multipliers'] if m]
        objective = {int(i): F(a) * S * D for i, a in cert['objective']}
        assert all(a.denominator == 1 for a in objective.values())
        fblocks = {}
        for i, a in objective.items():
            t, j = divmod(i, checker.J)
            if a:
                fblocks.setdefault(t, {})[j] = int(a)
        residual = [dict() for _ in range(checker.T)]
        for i, m in terms:
            for t, block in self.model.blocks(i).items():
                for j, a in block.items():
                    residual[t][j] = residual[t].get(j, 0) + m * a
        for t in range(checker.T):
            residual[t][0] = residual[t].get(0, 0) + mu * D
            for j, a in fblocks.get(t, {}).items():
                residual[t][j] = residual[t].get(j, 0) - a
            residual[t] = {j: a for j, a in residual[t].items() if a}
        errors = [-block.get(0, 0) * D + sum(max(-a, 0) * checker.U[j]
                  for j, a in block.items() if j) for block in residual]
        E = max(errors)
        upper = F(cert['upper'])
        assert (mu * D * D + E) * upper.denominator <= S * D * D * upper.numerator

        namespace = f'{BASE}.Witness{step}'
        spec = namespace + '.Spec'
        trees = Trees()
        obj_nodes = [(t, trees.tree(block, 8)) for t, block in sorted(fblocks.items())]
        entries = [(t, f'(.entry {t} {trees.render(node)})') for t, node in obj_nodes]
        def source(i):
            origin = self.model.graph['rows'][i]
            if origin[0] == 'lift':
                return f'(IntegerRow.lift {origin[2]} Data.bid{origin[1]})'
            return f'Data.row{i}'

        grouped = {}
        for i, m in terms:
            origin = self.model.graph['rows'][i]
            time = origin[2] if origin[0] == 'lift' else checker.T
            grouped.setdefault(time, []).append((i, m))
        lines, groups, group_proofs = [], [], []
        part_index = 0
        for time, group_terms in sorted(grouped.items()):
            group_parts = []
            for start in range(0, len(group_terms), 64):
                part = group_terms[start:start + 64]
                i = part_index
                part_index += 1
                group_parts.append(i)
                lines += [f'private def combinationPart{i} : StaticCombination := {combination(part, source)}',
                          f'private theorem matchesPart{i} : combinationPart{i}.Matches Data.rows := by\n'
                          f'  exact {conjunction(["(by rfl)" for _ in part])}']
            name = f'group{time}'
            lines += [f'private def {name} : StaticCombination := '
                      f'{add_combinations([f"combinationPart{i}" for i in group_parts])}',
                      f'private theorem matchesGroup{time} : {name}.Matches Data.rows := by\n'
                      f'  exact {conjunction([f"matchesPart{i}" for i in group_parts])}']
            if time < checker.T:
                lines.append(f'private theorem supportGroup{time} : {name}.onlyTime {time} = true := by decide +kernel')
                groups.append(f'(.atTime {time} {name})')
                group_proofs.append(f'⟨matchesGroup{time}, supportGroup{time}⟩')
            else:
                groups.append(name)
                group_proofs.append(f'matchesGroup{time}')
        lines += [f'def combination : StaticCombination := {add_combinations(groups)}',
                  'theorem rows_match : combination.Matches Data.rows := by\n'
                  f'  exact {conjunction(group_proofs)}',
                 f'def objective : IntegerRow := .blocks {lookup(entries)}',
                 f'def errorBound : ℤ := {E}',
                 f'theorem before : combination.shape.Before {cutoff} := by decide +kernel',
                 f'theorem reported_bound : (({mu} * {D} * {D} + errorBound) * {upper.denominator} : ℤ) ≤',
                 f'    {S} * {D} * {D} * ({upper.numerator}) := by decide +kernel']
        self.write(spec, [DATA + '.Rows', DATA + '.Budget', BASE + '.StaticWitness'], namespace, lines, trees)

        upper_scaled = upper * S * D
        assert upper_scaled.denominator == 1
        self.write(namespace + '.Bounds', [spec], namespace,
                   [f'def upperScaled : ℤ := {int(upper_scaled)}',
                    f'theorem scaled_report : ({mu} * {D} * {D} + errorBound : ℤ) ≤ {D} * upperScaled := by',
                    '  decide +kernel'])

        for t, block in enumerate(residual):
            trees = Trees()
            node = trees.tree(block, 8)
            lines = [f'def residual{t} : IntTree 8 := {trees.render(node)}',
                     f'theorem calculate{t} : residual{t} = IntTree.normalize (IntTree.add',
                     f'    (combination.block {t})',
                     f'    (IntTree.add (IntTree.constant ({mu} * {D}) 8)',
                     f'      (IntTree.scale (-1) (objective.block {t})))) := by ' +
                     ('rfl' if step == 4 else 'decide +kernel'),
                     f'theorem error{t} : IntTree.budgetError {D} residual{t} Data.budgetUpper ≤ errorBound := by',
                     '  decide +kernel']
            self.write(namespace + f'.Block{t:02}', [spec], namespace, lines, trees)

        index = lookup([(t, f'(.entry {t} residual{t})') for t in range(checker.T)])
        lines = [f'private def residualIndex : LookupTree (IntTree 8) := {index}',
                 'def residual (t : Fin 64) : IntTree 8 := residualIndex.get .zero t', '',
                 'theorem checked (w : Fin 64 → ℝ) (G : ℕ → ℝ)',
                 '    (hw : ∀ t, 0 ≤ w t) (hw1 : ∑ t, w t = 1)',
                 '    (hG : ∀ j < 256, 0 ≤ G j) (hG0 : G 0 = 1)',
                 f'    (hGU : ∀ j < 256, j ≠ 0 → ({D} : ℝ) * G j ≤ (Data.budgetUpper.coeff j : ℝ))',
                 f'    (hrows : ∀ i < {cutoff}, (Data.rows i).value w G ≤ 0) :',
                 f'    ({D} : ℝ) * objective.value w G ≤ (({mu} * {D} * {D} + errorBound : ℤ) : ℝ) := by',
                 f'  apply integer_static_witness Data.rows combination {cutoff} objective residual Data.budgetUpper',
                 f'    {D} ({mu}) errorBound w G (by decide) hw hw1 hG hG0 hGU before rows_match hrows',
                 '  · intro t', '    fin_cases t']
        lines += [f'    · exact calculate{t}' for t in range(checker.T)]
        lines += ['  · intro t', '    fin_cases t']
        lines += [f'    · exact error{t}' for t in range(checker.T)]
        lines += ['', 'theorem bound (w : Fin 64 → ℝ) (G : ℕ → ℝ)',
                  '    (hw : ∀ t, 0 ≤ w t) (hw1 : ∑ t, w t = 1)',
                  '    (hG : ∀ j < 256, 0 ≤ G j) (hG0 : G 0 = 1)',
                  f'    (hGU : ∀ j < 256, j ≠ 0 → ({D} : ℝ) * G j ≤ (Data.budgetUpper.coeff j : ℝ))',
                  f'    (hrows : ∀ i < {cutoff}, (Data.rows i).value w G ≤ 0) :',
                  '    objective.value w G ≤ (upperScaled : ℝ) := by',
                  '  have hraw := checked w G hw hw1 hG hG0 hGU hrows',
                  f'  have hreport : (({mu} * {D} * {D} + errorBound : ℤ) : ℝ) ≤',
                  f'      ({D} : ℝ) * (upperScaled : ℝ) := by exact_mod_cast scaled_report',
                  '  exact le_of_mul_le_mul_left (hraw.trans hreport) (by norm_num)']
        self.write(namespace + '.Checked', [namespace + f'.Block{t:02}' for t in range(checker.T)] +
                   [namespace + '.Bounds', 'Mathlib.Tactic.FinCases'], namespace, lines)
        self.objective_shape(step, fblocks, int(upper_scaled))
        return {'step': step, 'premises': len(terms), 'cutoff': cutoff, 'residual_error': str(E),
                'reported': str(upper), 'module': namespace + '.Checked'}

    def objective_shape(self, step, fblocks, upper_scaled):
        """Interpret a checked bound, independently of how that bound was proved."""
        namespace = f'{BASE}.Witness{step}'
        event = self.model.graph['witnesses'][step]
        imports = [namespace + '.Bounds', BASE + '.RowSoundness', 'Mathlib.Tactic.FinCases']
        trees = Trees()
        lines = []
        if event['kind'] == 'g':
            bid = next(i for i, desc in enumerate(self.model.graph['bids'])
                       if desc == ('derived', step))
            imports.append(self.owners[f'bid{bid}'])
            direction = fblocks[0]
            assert all(fblocks[t] == direction for t in range(self.model.checker.T))
            node = trees.tree(direction, 8)
            raw = direction.copy()
            raw[0] = raw.get(0, 0) - upper_scaled
            scale = self.model.checker.S * self.model.checker.D
            denominator = max([scale] + [abs(a) for a in raw.values()])
            lines += [f'def direction : IntTree 8 := {trees.render(node)}',
                      'theorem objective_blocks (t : Fin 64) : objective.block t = direction := by',
                      '  fin_cases t <;> rfl',
                      f'theorem rounded_direction : Data.bid{bid} = IntTree.normalize',
                      f'    (IntTree.floorScale {self.model.checker.D} {denominator}',
                      '      (IntTree.add direction (IntTree.constant (-upperScaled) 8))) := by rfl',
                      'theorem derived_bid_valid (w : Fin 64 → ℝ) (G : ℕ → ℝ)',
                      '    (hw1 : ∑ t, w t = 1) (hG : ∀ j < 256, 0 ≤ G j) (hG0 : G 0 = 1)',
                      '    (hbound : objective.value w G ≤ (upperScaled : ℝ)) :',
                      f'    Data.bid{bid}.eval G ≤ 0 := by',
                      '  rw [IntegerRow.common_value objective direction w G hw1 objective_blocks] at hbound',
                      '  exact IntTree.shifted_rounded_valid direction _ upperScaled _',
                      '    (by decide) (by decide) G hG hG0 hbound rounded_direction']
        elif event['kind'] == 'lambda':
            imports.append(DATA + '.Factors')
            lines += ['def coefficients (t : Fin 64) : ℤ := (objective.block t).coeff 0',
                      'theorem objective_blocks (t : Fin 64) :',
                      '    objective.block t = IntTree.normalize (IntTree.constant (coefficients t) 8) := by',
                      '  fin_cases t <;> rfl',
                      f'theorem denominators_positive : ∀ t : Fin 64, 0 < (Data.factors{step}.get (0, 1) t).2 := by',
                      '  decide +kernel',
                      f'theorem factor_coefficients : ∀ t : Fin 64, (Data.factors{step}.get (0, 1) t).1 *',
                      f'    {self.model.checker.S * self.model.checker.D} =',
                      f'      (upperScaled - coefficients t) * ((Data.factors{step}.get (0, 1) t).2 : ℤ) := by',
                      '  decide +kernel',
                      'theorem derived_factor_nonneg (w : Fin 64 → ℝ) (G : ℕ → ℝ)',
                      '    (hw1 : ∑ t, w t = 1) (hG0 : G 0 = 1)',
                      '    (hbound : objective.value w G ≤ (upperScaled : ℝ)) :',
                      f'    0 ≤ ∑ t : Fin 64, w t * ((Data.factors{step}.get (0, 1) t).1 : ℝ) /',
                      f'      ((Data.factors{step}.get (0, 1) t).2 : ℝ) := by',
                      '  rw [IntegerRow.scalar_value objective coefficients w G hG0 objective_blocks] at hbound',
                      f'  exact factor_total_nonneg coefficients Data.factors{step}',
                      f'    {self.model.checker.S * self.model.checker.D} upperScaled w (by decide) hw1 hbound',
                      '    denominators_positive factor_coefficients']
        else:
            assert event['kind'] == 'contradiction'
            lines += ['theorem impossible_bound (w : Fin 64 → ℝ) (G : ℕ → ℝ)',
                      '    (hbound : objective.value w G ≤ (upperScaled : ℝ)) : False := by',
                      '  norm_num [objective, IntegerRow.value, IntegerRow.block, LookupTree.get,',
                      '    IntTree.eval, upperScaled] at hbound']
        self.write(namespace + '.ObjectiveShape', imports, namespace, lines, trees)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--steps', default='4', help='comma-separated original witness steps, or all')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    model = CertificateModel(root)
    generator = Generator(model)
    generator.data()
    steps = sorted(model.graph['used_witnesses']) if args.steps == 'all' else [int(s) for s in args.steps.split(',')]
    reports = [generator.witness(step) for step in steps]
    print(json.dumps({'generated_modules': len(generator.files),
                      'source_bytes': sum(path.stat().st_size for path in generator.files),
                      'witnesses': reports}, indent=2))


if __name__ == '__main__':
    main()
